export function getServiceSlug(service: Service): string {
  if (service.slug) return service.slug
  return service.name
    .toLowerCase()
    .replace(/&/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

export function findService(idOrSlug: string): Service | undefined {
  if (!idOrSlug) return undefined
  const target = idOrSlug.trim().toLowerCase()
  return serviceCatalog.find(
    (s) =>
      s.id.toLowerCase() === target ||
      (s.slug && s.slug.toLowerCase() === target) ||
      getServiceSlug(s).toLowerCase() === target ||
      s.name.toLowerCase() === target ||
      s.name.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') === target
  )
}

